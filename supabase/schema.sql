-- Common Ground: crew stats & leaderboard
-- Paste this whole file into the Supabase SQL editor and run it. Safe to re-run.
--
-- Security model
--   * Tables have RLS on with no policies, and anon/authenticated have no table grants,
--     so the browser cannot read or write tables directly.
--   * The browser only calls three functions:
--       create_crew(name, pin)          -> make a crew, returns its code
--       submit_game(code, pin, game)    -> save a finished game (PIN required)
--       get_leaderboard(code)           -> read stats (knowing the code is enough)

create extension if not exists pgcrypto with schema extensions;

create table if not exists public.crews (
  id         uuid primary key default gen_random_uuid(),
  slug       text not null unique check (slug ~ '^[a-z0-9-]{3,40}$'),
  name       text not null check (char_length(name) between 1 and 40),
  pin_hash   text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.members (
  id         uuid primary key default gen_random_uuid(),
  crew_id    uuid not null references public.crews(id) on delete cascade,
  name       text not null,
  name_key   text not null,
  created_at timestamptz not null default now(),
  unique (crew_id, name_key)
);

create table if not exists public.games (
  id           uuid primary key,              -- generated by the host; makes saving idempotent
  crew_id      uuid not null references public.crews(id) on delete cascade,
  played_at    timestamptz not null default now(),
  rounds       int not null,
  player_count int not null
);
create index if not exists games_crew_idx on public.games (crew_id, played_at desc);

create table if not exists public.game_players (
  game_id       uuid not null references public.games(id) on delete cascade,
  member_id     uuid not null references public.members(id) on delete cascade,
  score         int not null default 0,
  place         int not null default 0,
  won           boolean not null default false,
  rounds        int not null default 0,  -- rounds this player was present for
  answered      int not null default 0,
  matched       int not null default 0,  -- rounds where at least one other player matched them
  lone          int not null default 0,  -- rounds where nobody matched them
  spot_turns    int not null default 0,  -- times they were in the spotlight
  spot_matchers int not null default 0,  -- total players who matched them while in the spotlight
  spot_tries    int not null default 0,  -- spotlight rounds where they tried to match someone
  spot_hits     int not null default 0,  -- ...and succeeded
  primary key (game_id, member_id)
);
create index if not exists game_players_member_idx on public.game_players (member_id);

create table if not exists public.game_pairs (
  game_id uuid not null references public.games(id) on delete cascade,
  a       uuid not null references public.members(id) on delete cascade,
  b       uuid not null references public.members(id) on delete cascade,
  matches int not null default 0,
  primary key (game_id, a, b),
  check (a < b)
);

alter table public.crews        enable row level security;
alter table public.members      enable row level security;
alter table public.games        enable row level security;
alter table public.game_players enable row level security;
alter table public.game_pairs   enable row level security;

revoke all on public.crews, public.members, public.games, public.game_players, public.game_pairs
  from anon, authenticated;

/* ---------------- helpers (not callable from the browser) ---------------- */

create or replace function public._cg_crew_auth(p_slug text, p_pin text)
returns uuid
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_id   uuid;
  v_hash text;
begin
  select id, pin_hash into v_id, v_hash from crews where slug = lower(trim(p_slug));
  if v_id is null then
    raise exception 'No crew with that code.';
  end if;
  if v_hash <> crypt(coalesce(p_pin, ''), v_hash) then
    raise exception 'Wrong crew PIN.';
  end if;
  return v_id;
end $$;

create or replace function public._cg_int(j jsonb, k text, hi int default 1000)
returns int
language sql
immutable
as $$
  select least(greatest(coalesce(round((j ->> k)::numeric)::int, 0), 0), hi)
$$;

create or replace function public._cg_name_key(n text)
returns text
language sql
immutable
as $$
  select lower(regexp_replace(trim(coalesce(n, '')), '\s+', ' ', 'g'))
$$;

revoke execute on function public._cg_crew_auth(text, text) from public, anon, authenticated;
revoke execute on function public._cg_int(jsonb, text, int) from public, anon, authenticated;
revoke execute on function public._cg_name_key(text) from public, anon, authenticated;

/* ---------------- public API ---------------- */

create or replace function public.create_crew(p_name text, p_pin text)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_name text := left(trim(coalesce(p_name, '')), 40);
  v_base text;
  v_slug text;
  v_alpha text := 'abcdefghjkmnpqrstuvwxyz23456789';
  i int;
begin
  if v_name = '' then raise exception 'Give your crew a name.'; end if;
  if char_length(coalesce(p_pin, '')) < 4 or char_length(p_pin) > 32 then
    raise exception 'PIN must be 4 to 32 characters.';
  end if;
  v_base := trim(both '-' from left(regexp_replace(lower(v_name), '[^a-z0-9]+', '-', 'g'), 20));
  if v_base = '' then v_base := 'crew'; end if;
  loop
    v_slug := v_base || '-';
    for i in 1..4 loop
      v_slug := v_slug || substr(v_alpha, 1 + floor(random() * length(v_alpha))::int, 1);
    end loop;
    exit when not exists (select 1 from crews where slug = v_slug);
  end loop;
  insert into crews (slug, name, pin_hash) values (v_slug, v_name, crypt(p_pin, gen_salt('bf')));
  return jsonb_build_object('slug', v_slug, 'name', v_name);
end $$;

-- Check a code + PIN without saving anything (used when linking a crew to a room).
create or replace function public.check_crew(p_slug text, p_pin text)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_id uuid := _cg_crew_auth(p_slug, p_pin);
begin
  return (select jsonb_build_object('slug', slug, 'name', name) from crews where id = v_id);
end $$;

-- p_game: { id, rounds, players: [{name, score, place, won, rounds, answered, matched, lone,
--           spotTurns, spotMatchers, spotTries, spotHits}], pairs: [{a, b, n}] }   (a/b are names)
create or replace function public.submit_game(p_slug text, p_pin text, p_game jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_crew uuid := _cg_crew_auth(p_slug, p_pin);
  v_game uuid;
  v_n    int := jsonb_array_length(coalesce(p_game -> 'players', '[]'::jsonb));
  p      jsonb;
  v_key  text;
  v_mid  uuid;
  v_a    uuid;
  v_b    uuid;
begin
  begin
    v_game := (p_game ->> 'id')::uuid;
  exception when others then
    raise exception 'Bad game id.';
  end;
  if v_game is null then raise exception 'Bad game id.'; end if;
  if v_n < 2 or v_n > 12 then raise exception 'A saved game needs 2 to 12 players.'; end if;

  insert into games (id, crew_id, rounds, player_count)
  values (v_game, v_crew, greatest(_cg_int(p_game, 'rounds', 50), 1), v_n)
  on conflict (id) do nothing;
  if not found then
    return jsonb_build_object('ok', true, 'duplicate', true);
  end if;

  for p in select value from jsonb_array_elements(p_game -> 'players') loop
    v_key := _cg_name_key(p ->> 'name');
    continue when v_key = '';
    insert into members (crew_id, name, name_key)
    values (v_crew, left(regexp_replace(trim(p ->> 'name'), '\s+', ' ', 'g'), 16), v_key)
    on conflict (crew_id, name_key) do update set name = excluded.name
    returning id into v_mid;

    insert into game_players (game_id, member_id, score, place, won, rounds, answered, matched, lone,
                              spot_turns, spot_matchers, spot_tries, spot_hits)
    values (v_game, v_mid,
            _cg_int(p, 'score'), _cg_int(p, 'place', 12), coalesce((p ->> 'won')::boolean, false),
            _cg_int(p, 'rounds', 50), _cg_int(p, 'answered', 50), _cg_int(p, 'matched', 50), _cg_int(p, 'lone', 50),
            _cg_int(p, 'spotTurns', 50), _cg_int(p, 'spotMatchers', 600), _cg_int(p, 'spotTries', 50), _cg_int(p, 'spotHits', 50))
    on conflict do nothing;
  end loop;

  for p in select value from jsonb_array_elements(coalesce(p_game -> 'pairs', '[]'::jsonb)) loop
    select id into v_a from members where crew_id = v_crew and name_key = _cg_name_key(p ->> 'a');
    select id into v_b from members where crew_id = v_crew and name_key = _cg_name_key(p ->> 'b');
    continue when v_a is null or v_b is null or v_a = v_b;
    insert into game_pairs (game_id, a, b, matches)
    values (v_game, least(v_a, v_b), greatest(v_a, v_b), _cg_int(p, 'n', 50))
    on conflict (game_id, a, b) do update set matches = game_pairs.matches + excluded.matches;
  end loop;

  return jsonb_build_object('ok', true, 'duplicate', false);
end $$;

create or replace function public.get_leaderboard(p_slug text)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, extensions
as $$
declare
  v_crew crews%rowtype;
begin
  select * into v_crew from crews where slug = lower(trim(p_slug));
  if v_crew.id is null then raise exception 'No crew with that code.'; end if;

  return jsonb_build_object(
    'crew', jsonb_build_object(
      'name', v_crew.name,
      'slug', v_crew.slug,
      'games', (select count(*) from games where crew_id = v_crew.id)
    ),
    'players', coalesce((
      select jsonb_agg(to_jsonb(x) order by x.wins desc, x.points desc)
      from (
        select m.name,
               count(*)::int                         as games,
               count(*) filter (where gp.won)::int   as wins,
               sum(gp.rounds)::int                   as rounds,
               sum(gp.answered)::int                 as answered,
               sum(gp.matched)::int                  as matched,
               sum(gp.lone)::int                     as lone,
               sum(gp.score)::int                    as points,
               sum(gp.spot_turns)::int               as spot_turns,
               sum(gp.spot_matchers)::int            as spot_matchers,
               sum(gp.spot_tries)::int               as spot_tries,
               sum(gp.spot_hits)::int                as spot_hits,
               max(g.played_at)                      as last_played
        from members m
        join game_players gp on gp.member_id = m.id
        join games g on g.id = gp.game_id
        where m.crew_id = v_crew.id
        group by m.id, m.name
      ) x
    ), '[]'::jsonb),
    'pairs', coalesce((
      select jsonb_agg(to_jsonb(y) order by y.matches desc)
      from (
        select ma.name as a, mb.name as b,
               sum(gp.matches)::int                     as matches,
               count(*)::int                            as games,
               sum(least(pa.rounds, pb.rounds))::int    as shared
        from game_pairs gp
        join members ma on ma.id = gp.a
        join members mb on mb.id = gp.b
        join game_players pa on pa.game_id = gp.game_id and pa.member_id = gp.a
        join game_players pb on pb.game_id = gp.game_id and pb.member_id = gp.b
        where ma.crew_id = v_crew.id
        group by ma.id, ma.name, mb.id, mb.name
      ) y
    ), '[]'::jsonb),
    'recent', coalesce((
      select jsonb_agg(to_jsonb(z) order by z.played_at desc)
      from (
        select g.played_at, g.rounds, g.player_count,
               (select coalesce(jsonb_agg(m.name order by m.name), '[]'::jsonb)
                  from game_players gp join members m on m.id = gp.member_id
                 where gp.game_id = g.id and gp.won) as winners
        from games g
        where g.crew_id = v_crew.id
        order by g.played_at desc
        limit 8
      ) z
    ), '[]'::jsonb)
  );
end $$;

